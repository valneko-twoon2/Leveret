"""Generates leveret.svg: a young hare sitting, as a plain white silhouette with
slightly uneven (hand-drawn) edges, on a crisp rounded square.

Each shape of the hare is traced with jittered points and smoothed into curves;
the output is deterministic (fixed seed).

Usage: python backend/icons/generate_icon.py
Then:  frontend/node_modules/.bin/tauri icon backend/icons/leveret.svg -o backend/icons
"""

import math
import random
from pathlib import Path

OUT = Path(__file__).with_name("leveret.svg")
FUR = "#ffffff"

# A young hare sitting, facing right: (cx, cy, rx, ry, rotation in degrees).
HARE = [
    (545, 300, 44, 150, -38),  # back ear
    (610, 275, 50, 165, -22),  # front ear
    (660, 455, 128, 112, -12),  # head
    (575, 560, 125, 135, 0),  # neck
    (465, 655, 235, 185, -8),  # body
    (370, 700, 150, 150, 0),  # haunch
    (238, 610, 52, 52, 0),  # tail
    (618, 812, 84, 34, 0),  # front paw
]


def smooth_path(points):
    """Closed Catmull-Rom spline through points, as an SVG path."""
    n = len(points)
    d = f"M{points[0][0]:.1f} {points[0][1]:.1f}"
    for i in range(n):
        p0, p1, p2, p3 = points[i - 1], points[i], points[(i + 1) % n], points[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]:.1f} {p2[1]:.1f}"
    return d + "Z"


def ellipse(rng, cx, cy, rx, ry, rot=0.0, jitter=0.03, steps=18):
    a = math.radians(rot)
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        k = 1 + rng.uniform(-jitter, jitter)
        x, y = rx * k * math.cos(t), ry * k * math.sin(t)
        pts.append((cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)))
    return smooth_path(pts)


def main():
    rng = random.Random(11)
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">',
        "  <!-- Generated by generate_icon.py. Edit the script, not this file. -->",
        '  <defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">'
        '<stop offset="0" stop-color="#ffb35c"/><stop offset="1" stop-color="#f2665a"/></linearGradient></defs>',
        '  <rect x="64" y="64" width="896" height="896" rx="220" fill="url(#bg)"/>',
        f'  <g fill="{FUR}">',
        *[f'    <path d="{ellipse(rng, *shape)}"/>' for shape in HARE],
        "  </g>",
        "</svg>",
    ]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
